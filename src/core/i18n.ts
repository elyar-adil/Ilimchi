/**
 * 界面语言：跟随系统语言自动选择（系统首选语言为中文则用中文，否则英文）。
 * 文案以中文原文作为键；英文译文见 EN。缺译时回退到中文。
 */

export type Lang = 'zh' | 'en';

function detectLang(): Lang {
  try {
    const list = navigator.languages?.length ? navigator.languages : [navigator.language];
    const first = list.find((l) => !!l) ?? 'en';
    return /^zh\b/i.test(first) ? 'zh' : 'en';
  } catch {
    return 'en';
  }
}

export const LANG: Lang = detectLang();

type Vars = Record<string, string | number>;

/** 翻译：`tr('共 {n} 篇', { n: 3 })`。占位符以 {name} 书写。 */
export function tr(zh: string, vars?: Vars): string {
  let s = LANG === 'en' ? (EN[zh] ?? zh) : zh;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
  return s;
}

